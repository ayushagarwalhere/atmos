import { test, expect } from '@playwright/test';
test('smog sequence, recovery, city selection and manifest export', async ({ page }) => {
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/');
  await expect(page.locator('.preloader')).toHaveCount(0,{timeout:20000});
  await expect(page.getByRole('heading',{name:'A little algae. A better atmosphere.'})).toBeVisible();
  await expect(page.locator('main')).not.toHaveAttribute('inert','');
  await page.locator('#demo').scrollIntoViewIfNeeded();
  await expect(page.locator('.aqi-reading>span')).toHaveText('78');
  await expect(page.locator('.device-metrics strong').first()).toHaveText('25%');
  await page.getByRole('button',{name:'Simulate smog event'}).click();
  await expect(page.locator('.aqi-reading>span')).toHaveText('412');
  await expect(page.locator('.device-metrics strong').first()).toHaveText('25%');
  await expect(page.locator('.device-metrics strong').first()).toHaveText('100%',{timeout:10000});
  await expect(page.locator('.alert-preview strong')).toHaveText('Classroom 4B · Alert preview',{timeout:10000});
  await expect(page.locator('.pipeline .complete')).toHaveCount(4);
  const downloadPromise=page.waitForEvent('download');
  await page.getByRole('button',{name:'Export manifest'}).click();
  const download=await downloadPromise;
  expect(download.suggestedFilename()).toBe('algaeair-demo-manifest.json');
  const fs=await import('node:fs/promises');
  const manifest=JSON.parse(await fs.readFile(await download.path(),'utf8'));
  expect(manifest.dataSource).toBe('local-simulation');expect(manifest.awsConnected).toBe(false);expect(manifest.pumpPercent).toBe(100);expect(manifest.carbonReduction).toBe(null);
  await page.getByRole('button',{name:'Return to clean-air baseline'}).click();
  await expect(page.locator('.aqi-reading>span')).toHaveText('78');
  await expect(page.locator('.device-metrics strong').first()).toHaveText('25%');
  await page.getByLabel('Monitoring city').selectOption('Mumbai');
  await expect(page.locator('.aqi-reading>span')).toHaveText('64');
  await page.getByLabel('Simulated India AQI').fill('260');
  await expect(page.locator('.device-metrics strong').first()).toHaveText('75%');
  await page.getByRole('button',{name:'Reset demo'}).click();
  await expect(page.locator('.aqi-reading>span')).toHaveText('64');
  await page.getByRole('button',{name:'Simulate smog event'}).click();
  await page.getByRole('button',{name:'Reset demo'}).click();
  await page.waitForTimeout(4600);
  await expect(page.locator('.pipeline .complete')).toHaveCount(0);
  expect(errors).toEqual([]);
});
test('mobile layout, menu, reduced motion and intro replay', async ({page}) => {
  await page.setViewportSize({width:390,height:844});
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.goto('/');
  await expect(page.locator('.preloader')).toHaveCount(0,{timeout:20000});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.getByRole('button',{name:'Open navigation'}).click();
  await page.getByRole('navigation',{name:'Mobile navigation'}).getByRole('link',{name:'Try the response'}).click();
  await expect(page.getByRole('navigation',{name:'Mobile navigation'})).toHaveCount(0);
  await expect(page.getByRole('button',{name:'Simulate smog event'})).toBeVisible();
  await expect(page.getByRole('button',{name:'Motion off'})).toHaveAttribute('aria-pressed','true');
  await page.getByRole('button',{name:'Replay intro'}).click();
  await expect(page.locator('.preloader')).toHaveCount(0,{timeout:10000});
  await expect(page.locator('main')).not.toHaveAttribute('inert','');
});

